#!/usr/bin/env node
// github-wiki-codemod.mjs — the mechanical part of a GitHub wiki → Blume
// migration. Run it from a copy of the wiki clone, which becomes the Blume
// project (`blume.config.ts` beside it, pages moved into `docs/`). It has four
// commands:
//
//   routes   Lists the wiki's pages the way GitHub serves them (every file in a
//            markup format GitHub renders, named by its file name, folders
//            ignored, a root file winning a name clash) and writes the route
//            table: `wiki-routes.json` (page name → new flat route) and
//            `wiki-files.json` (page name → file). It suggests which pages are
//            moved notices or not content, for you to classify by editing the
//            table (a target URL or route, or `null`). It never overwrites a
//            table that exists: it compares the two instead.
//   convert  Reads the classified table and, per Markdown page that stays:
//            moves it to `docs/(group)/<route>.md` (`Home` → `docs/index.md`),
//            writes `title` (the page name as GitHub showed it), `sidebar.label`,
//            and `slug` where the file's place doesn't give its route; turns
//            `[[wiki links]]` (text first, `[[Page]]`, `[[text|Page#anchor]]`,
//            `[[text|https://…]]`, image tags, `[[_TOC_]]`) and links to the
//            wiki (absolute, root-relative, bare page names, `#user-content-`
//            anchors, the mirror repository's copies, relative links that leave
//            the wiki) into routes; moves the wiki's own images next to the
//            pages and points them there (Markdown images, wiki image tags, and
//            a raw `<img>` alone on its line), dropping a relative image that
//            pointed at nothing on GitHub either; converts GitHub alerts to `:::`
//            directives (an indented or lazy one stays an alert, which Blume
//            renders as a callout in `.mdx`); lowercases fence languages (Blume
//            reads any case, so that only tidies) and maps Linguist-only ones;
//            pins `<a name>` heading anchors as `[#id]` (Blume would take the
//            name as the id anyway; the pin drops the empty tag); deletes a
//            leading H1 that repeats the page name
//            and demotes every heading one level on a page that still has an H1
//            (ATX and one-line setext); deletes a Foam "Autogenerated link
//            references" block and link definitions a same-label one above
//            already shadows (CommonMark uses the first); and renames a page
//            that now needs MDX to `.mdx` with its comments, void tags,
//            autolinks, bare `<`, and braces made MDX-safe. It writes a
//            `meta.ts` per `_Sidebar.md` group, a root one in sidebar order, and
//            a collapsed "More pages" group for the pages the sidebar doesn't
//            list. It leaves fenced, indented, and inline code, `<code>` and
//            `<tt>`, HTML comments, and gollum's `'[[…]]` escape alone, and
//            writes a wiki link inside an HTML block as `<a href>`, since
//            Markdown there shows as text.
//   stubs    In a fresh clone of the wiki (with both tables copied in),
//            replaces every page with a one-line link to its new URL and the
//            sidebar with a notice. It only writes files: it never commits or
//            pushes, and it refuses to run beside a `blume.config.ts`. The
//            user pushes. `--notice-only` only puts the notice at the top of
//            `Home` and `_Sidebar.md`.
//   check    After `blume build`: every route in the table must exist in
//            `dist/`, anchors included. Given old wiki URLs (inbound links from
//            the main repository), it prints each one's new route and checks
//            its page and anchor, suggesting ids for an anchor that's gone.
//
// It reports, and never fakes, what needs judgment: pages in other markup
// formats (convert them with pandoc first), sidebar lines it can't place,
// wiki links to missing or left-out pages (made plain text), Markdown links
// that were already broken on GitHub (left for you to retarget), wiki UI links,
// files stored in the wiki that pages link or show in raw HTML, uploaded
// attachments to vendor, dropped images and image sizes, multi-line setext
// headings, emoji in headings, MDX hazards it can't fix, and the files a
// converted copy leaves behind.
//
// Design constraints (as mintlify-codemod.mjs): zero dependencies, sorted and
// deterministic, idempotent (a second run changes nothing), dry run by default.
//
// Usage, from the copy of the wiki clone:
//   node github-wiki-codemod.mjs routes --repo owner/repo            # report
//   node github-wiki-codemod.mjs routes --repo owner/repo --write    # write the table
//   node github-wiki-codemod.mjs convert --repo owner/repo           # dry run
//   node github-wiki-codemod.mjs convert --repo owner/repo --write   # apply
//   node github-wiki-codemod.mjs stubs --site https://docs.example.com --write
//   node github-wiki-codemod.mjs check [https://github.com/owner/repo/wiki/FAQ#x …]
//
// Options:
//   --repo <owner/repo>   The repository the wiki belongs to (routes, convert).
//   --mirror <owner/repo> A repository that mirrors the wiki (`<repo>-wiki`):
//                         links to its copies of pages become routes too.
//   --content <dir>       The content root (default: docs).
//   --emoji <file>        Shortcode → emoji map (GitHub's /emojis JSON works).
//   --site <url>          The new site, base path included (stubs).
//   --notice-only         Stubs: only the notice on Home and the sidebar.
//   --dist <dir>          The build to check (default: dist).
//   --write               Apply. Without it, report only.

