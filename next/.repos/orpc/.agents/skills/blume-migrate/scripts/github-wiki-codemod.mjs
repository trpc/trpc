const createPage = (file, name) => ({
  edits: {},
  file,
  name,
  reviews: [],
});

const edit = (page, kind, count = 1) => {
  page.edits[kind] = (page.edits[kind] ?? 0) + count;
};

const review = (page, line, message) => {
  page.reviews.push({ line, message });
};

// --- Links and images -----------------------------------------------------------

/** An image source → its new source, "" to drop an image GitHub couldn't show either, or null (keep). */
const rewriteImage = (ctx, rawSrc) => {
  const src = unwrapAngle(rawSrc);
  if (ctx.done.has(src)) {
    return null;
  }
  const found = wikiFileOf(ctx, src);
  const relative = !URL_SCHEME.test(src) && !src.startsWith("/");
  if (found?.outside || (found && relative && !ctx.fileExists(found.file))) {
    review(
      ctx.page,
      ctx.line,
      `image ${src} pointed at nothing on GitHub (${found.outside ? "above the wiki root" : "no such file"}): dropped`
    );
    edit(ctx.page, "broken image dropped");
    return "";
  }
  if (found && !ctx.fileExists(found.file)) {
    review(
      ctx.page,
      ctx.line,
      `image ${src} names a file the wiki doesn't have`
    );
    return null;
  }
  if (found) {
    ctx.images.add(found.file);
    edit(ctx.page, "wiki image → file beside the pages");
    const moved = relativeAsset(ctx.dest, `${ctx.content}/${found.file}`);
    ctx.done.add(moved);
    return moved;
  }
  if (ATTACHMENT.test(src)) {
    review(ctx.page, ctx.line, `uploaded attachment ${src}: vendor it`);
    return null;
  }
  const blob = BLOB.exec(src);
  if (blob) {
    edit(ctx.page, "blob image URL → raw URL");
    return `https://raw.githubusercontent.com/${blob.groups.owner}/${blob.groups.repo}/${blob.groups.rest}`;
  }
  return null;
};

/** A page target → `{ href }`; a wiki link to a missing page, or any link to a left-out page, → `{ unlink }`. */
const pageHref = (ctx, target, how, hint = "") => {
  const result = resolvePage(ctx.index, target, ctx.name);
  if (result.kind === "missing" && how !== "[[wiki link]]") {
    review(
      ctx.page,
      ctx.line,
      `${how} ${target} names no page in the wiki, so it was broken on GitHub too: retarget it or unlink it`
    );
    return null;
  }
  if (result.kind === "missing" || result.kind === "dropped") {
    const why =
      result.kind === "missing"
        ? "names no page in the wiki"
        : "names a page you left out";
    review(
      ctx.page,
      ctx.line,
      `${how} ${target} ${why}: made plain text${hint}`
    );
    return { unlink: true };
  }
  if (result.kind === "moved") {
    edit(ctx.page, `${how} to a moved page → its target`);
  } else {
    edit(ctx.page, `${how} → route`);
  }
  return { href: result.href };
};

/** A Markdown or HTML link destination → `{ href }`, `{ unlink: true }`, or null (keep). */
const anchorHref = (ctx, dest) => {
  const anchor = cleanAnchor(dest.slice(1));
  if (anchor === dest.slice(1)) {
    return null;
  }
  edit(ctx.page, "#user-content- anchor → its id");
  return { href: `#${anchor}` };
};

/** A root path: into the wiki (handled with absolute URLs), elsewhere in the repository, or neither. */
const rootPathHref = (ctx, dest) => {
  if (ctx.urls.wiki.test(dest)) {
    return { wiki: true };
  }
  if (ctx.urls.repoRoot.test(dest)) {
    edit(ctx.page, "repository path → absolute GitHub URL");
    return { href: `https://github.com${dest}` };
  }
  return null;
};

const wikiHref = (ctx, dest, target, relative) => {
  if (target.kind === "ui") {
    review(
      ctx.page,
      ctx.line,
      `${dest} points at the wiki's UI: it stops working with the wiki`
    );
    return null;
  }
  if (target.kind === "file") {
    review(
      ctx.page,
      ctx.line,
      `${dest} links ${target.file}, a file stored in the wiki: copy it to public/ and link /${target.file}`
    );
    return null;
  }
  if (target.kind === "unknown") {
    review(
      ctx.page,
      ctx.line,
      `${dest} names no page or file in the wiki, so it was broken on GitHub too: retarget it or unlink it`
    );
    return null;
  }
  const result = pageHref(
    ctx,
    decode(target.target),
    relative ? "page-name link" : "wiki URL"
  );
  if (target.raw && result?.href) {
    review(
      ctx.page,
      ctx.line,
      `${dest} opened the page's raw file on GitHub: now its page`
    );
  }
  return result;
};

/** A Markdown or HTML link destination → `{ href }`, `{ unlink: true }`, or null (keep). */
const rewriteHref = (ctx, rawDest) => {
  const dest = unwrapAngle(rawDest);
  if (dest.startsWith("#")) {
    return anchorHref(ctx, dest);
  }
  const mirrored = ctx.urls.mirror?.exec(dest);
  if (mirrored && MARKUP.test(mirrored.groups.file)) {
    const name = pageNameOf(decode(mirrored.groups.file));
    return pageHref(ctx, `${name}${mirrored.groups.hash ?? ""}`, "mirror link");
  }
  if (dest.startsWith("/") && !dest.startsWith("//")) {
    const rooted = rootPathHref(ctx, dest);
    if (rooted === null || rooted.href) {
      return rooted;
    }
  }
  const relative =
    !URL_SCHEME.test(dest) && !dest.startsWith("/") && dest !== "";
  const absolute = relative
    ? resolveUrl(dest, `${ctx.urls.base}${encodeURIComponent(ctx.name)}`)
    : dest;
  const target = absolute === null ? null : wikiTarget(ctx, absolute);
  if (target !== null) {
    return wikiHref(ctx, dest, target, relative);
  }
  if (relative && absolute !== null) {
    edit(ctx.page, "relative link outside the wiki → absolute GitHub URL");
    return { href: absolute };
  }
  return null;
};

const escapeHtml = (text) =>
  text
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");

/** A link in the page's syntax: Markdown, or `<a>` inside an HTML block, where Markdown stays literal. */
const linkMarkup = (ctx, text, href) => {
  if (!ctx.html) {
    return `[${text}](${href})`;
  }
  edit(ctx.page, "link in an HTML block written as <a href>");
  return `<a href="${escapeHtml(href)}">${escapeHtml(text)}</a>`;
};

/** A wiki image tag's path: `/x.png` is the wiki root; a path the root lacks may sit in the page's folder. */
const imageTagPath = (ctx, first) => {
  const file = first.replace(/^\/(?!\/)/u, "");
  const folder = posix.dirname(ctx.page.file);
  if (
    URL_SCHEME.test(file) ||
    ctx.fileExists(file) ||
    folder === "." ||
    !ctx.fileExists(posix.join(folder, file))
  ) {
    return file;
  }
  review(
    ctx.page,
    ctx.line,
    `image ${first} found only in the page's folder (${folder}/), which is where gollum looks: check the live page`
  );
  return posix.join(folder, file);
};

/** `[[image.png|alt=Text,frame]]`: an image whenever the first part names one, as on GitHub. */
const convertImageTag = (ctx, first, parts) => {
  const options = parts
    .slice(1)
    .flatMap((part) => part.split(","))
    .map((option) => option.trim())
    .filter(Boolean);
  const alt =
    options
      .find((option) => /^alt\s*=/iu.test(option))
      ?.replace(/^alt\s*=\s*/iu, "") ?? "";
  const dropped = options.filter((option) => !/^alt\s*=/iu.test(option));
  if (dropped.length > 0) {
    review(ctx.page, ctx.line, `image options dropped: ${dropped.join(", ")}`);
  }
  const file = imageTagPath(ctx, first);
  const src = rewriteImage(ctx, file);
  if (src === "") {
    return "";
  }
  if (ctx.html) {
    review(
      ctx.page,
      ctx.line,
      `[[${first}]] sits in an HTML block, where a Markdown image shows as text: write it as <img src="${src ?? file}" />, which Blume publishes with the page, or move the image out of the block`
    );
  }
  edit(ctx.page, "[[image]] → Markdown image");
  return `![${alt}](${src ?? file})`;
};

/** A wiki link's target that names a file stored in the wiki (`[[Spec|docs/spec.pdf]]`), not a page. */
const isWikiFile = (ctx, target) => {
  const file = target.replace(/^\//u, "");
  return (
    posix.extname(file) !== "" &&
    !MARKUP.test(file) &&
    findPage(ctx.index, file) === null &&
    ctx.fileExists(file)
  );
};

/** For `[[Page|text]]` in a Markdown page: the target-first order GitHub's docs show, which only MediaWiki pages use. */
const swappedHint = (ctx, parts) => {
  if (
    parts.length !== 2 ||
    resolvePage(ctx.index, parts[1].trim(), ctx.name).kind !== "missing" ||
    resolvePage(ctx.index, parts[0].trim(), ctx.name).kind === "missing"
  ) {
    return "";
  }
  return ` (${parts[0].trim()} is a page: a Markdown page puts the text first, so GitHub showed a link to a missing page too)`;
};

const convertWikiLink = (ctx, inner) => {
  const parts = inner.split(PIPE);
  const first = parts[0].trim();
  if (first === "_TOC_") {
    edit(ctx.page, "[[_TOC_]] removed");
    return "";
  }
  if (IMAGE.test(first.split("#")[0])) {
    return convertImageTag(ctx, first, parts);
  }
  if (parts.length > 2) {
    review(
      ctx.page,
      ctx.line,
      `[[${inner}]] has more than one |: convert it by hand`
    );
    return null;
  }
  const text = first;
  const target = (parts[1] ?? parts[0]).trim();
  if (EXTERNAL.test(target)) {
    edit(ctx.page, "[[text|URL]] → link");
    return linkMarkup(ctx, text, target);
  }
  if (isWikiFile(ctx, target)) {
    review(
      ctx.page,
      ctx.line,
      `[[${inner}]] links ${target}, a file stored in the wiki: copy it to public/ and link /${target.replace(/^\//u, "")}`
    );
    return null;
  }
  const result = pageHref(
    ctx,
    target,
    "[[wiki link]]",
    swappedHint(ctx, parts)
  );
  return result.unlink ? text : linkMarkup(ctx, text, result.href);
};

/** One `[[…]]` match: `'[[…]]` stays (gollum's escape), the rest convert. */
const convertWikiMatch = (ctx, group) => {
  const quote = group("quote");
  const after = group("after");
  if (quote && !after) {
    review(
      ctx.page,
      ctx.line,
      `'[[${group("inner")}]] is gollum's escape for literal brackets, so it was left as is: check the live page, and drop the ' if it showed the brackets`
    );
    return null;
  }
  const converted = convertWikiLink(ctx, group("inner"));
  return converted === null ? null : `${quote}${converted}${after}`;
};

const convertImages = (ctx, line) =>
  replaceOutside(line, MD_IMAGE, (group) => {
    const src = rewriteImage(ctx, group("dest"));
    if (src === null || src === "") {
      return src;
    }
    return `![${group("alt")}](${src}${group("title") ?? ""})`;
  });

const convertLinks = (ctx, line) =>
  replaceOutside(line, MD_LINK, (group) => {
    const label = group("label");
    const result = rewriteHref(ctx, group("dest"));
    if (result === null) {
      return null;
    }
    if (result.unlink) {
      return label;
    }
    const title = group("title") ?? "";
    // Pandoc writes a MediaWiki link's text as its title too.
    const keepTitle = title && title.trim().slice(1, -1) !== label;
    return `[${label}](${result.href}${keepTitle ? title : ""})`;
  });

const convertRawHrefs = (ctx, line) =>
  replaceOutside(line, RAW_HREF, (group, original) => {
    const dest = group("dest");
    const result = rewriteHref(ctx, dest);
    if (result === null || result.unlink) {
      return null;
    }
    return original.replace(dest, result.href);
  });

const urlReplacement = (ctx, url) => {
  const target = wikiTarget(ctx, url);
  if (target?.kind !== "page") {
    review(ctx.page, ctx.line, `bare wiki URL left as is: ${url}`);
    return null;
  }
  const result = resolvePage(ctx.index, decode(target.target), ctx.name);
  if (result.kind === "missing" || result.kind === "dropped") {
    review(
      ctx.page,
      ctx.line,
      `bare wiki URL to a page that isn't kept: ${url}`
    );
    return null;
  }
  edit(ctx.page, "bare wiki URL → link");
  return linkMarkup(ctx, titleOf(result.name), result.href);
};

const convertBareUrls = (ctx, line) => {
  const angled = replaceOutside(line, ctx.urls.angle, (group) =>
    urlReplacement(ctx, group("url"))
  );
  return replaceOutside(angled, ctx.urls.bare, (group) => {
    const url = group("url");
    const trail = TRAILING_PUNCTUATION.exec(url)?.[0] ?? "";
    const link = urlReplacement(ctx, url.slice(0, url.length - trail.length));
    return link === null ? null : `${link}${trail}`;
  });
};

const convertEmoji = (ctx, line, heading) =>
  replaceOutside(
    line,
    SHORTCODE,
    (group, original) => {
      const emoji = ctx.emoji.get(group("name"));
      if (!emoji) {
        return null;
      }
      if (heading) {
        review(
          ctx.page,
          ctx.line,
          `${original} in a heading: GitHub's id spelled the name; convert it and pin the old id with [#…]`
        );
        return null;
      }
      edit(ctx.page, "emoji shortcode → emoji");
      return emoji;
    },
    { destinations: true }
  );

/** `\[\[…\]\]` is how pandoc writes a wiki link; in a page that was always Markdown, GitHub showed the brackets. */
const convertEscapedWikiLink = (ctx, inner) => {
  const converted = convertWikiLink(ctx, inner.replaceAll(String.raw`\|`, "|"));
  if (converted !== null) {
    review(
      ctx.page,
      ctx.line,
      String.raw`\[\[${inner}\]\] read as a wiki link (pandoc's escape): if this page was Markdown on GitHub, it showed the brackets, so restore them`
    );
  }
  return converted;
};

const convertInline = (ctx, line, heading = false) => {
  let next = replaceOutside(
    line,
    WIKI_LINK,
    (group) => convertWikiMatch(ctx, group),
    { elements: true }
  );
  next = replaceOutside(
    next,
    ESCAPED_WIKI_LINK,
    (group) => convertEscapedWikiLink(ctx, group("inner")),
    { elements: true }
  );
  next = convertImages(ctx, next);
  next = convertLinks(ctx, next);
  next = convertRawHrefs(ctx, next);
  next = convertBareUrls(ctx, next);
  return ctx.emoji.size > 0 ? convertEmoji(ctx, next, heading) : next;
};

// --- Line structure -------------------------------------------------------------

const indentWidth = (text) =>
  [...text].reduce((width, char) => width + (char === "\t" ? 4 : 1), 0);

/**
 * One state per line: `open`/`fence`/`close` for fenced code (any indent, in
 * a quote or not), `comment` inside a multi-line HTML comment, `indented` for
 * indented code, `prose` otherwise.
 */
const closesFence = (fence, line) => {
  const close = FENCE.exec(line);
  return (
    close?.groups.marker[0] === fence.char &&
    close.groups.marker.length >= fence.length &&
    close.groups.info.trim() === ""
  );
};

const opensFence = (line) => {
  const open = FENCE.exec(line);
  if (
    open === null ||
    (open.groups.marker.startsWith("`") && open.groups.info.includes("`"))
  ) {
    return null;
  }
  return { char: open.groups.marker[0], length: open.groups.marker.length };
};

/** The content column of the list a line belongs to, or -1 outside lists. */
const nextListIndent = (line, listIndent) => {
  if (line.trim() === "") {
    return listIndent;
  }
  const width = indentWidth(/^[ \t]*/u.exec(line)[0]);
  const item = LIST_ITEM.exec(line);
  if (item && width < listIndent + 4) {
    return indentWidth(
      `${item.groups.indent}${item.groups.marker}${item.groups.gap}`
    );
  }
  return width === 0 ? -1 : listIndent;
};

/**
 * One state per line: `open`/`fence`/`close` for fenced code (any indent, in
 * a quote or not), `comment` inside a multi-line HTML comment, `indented` for
 * indented code, `prose` otherwise.
 */
const lineStates = (lines) => {
  const states = [];
  let fence = null;
  let comment = false;
  let previousBlank = true;
  let listIndent = -1;
  for (const line of lines) {
    if (fence) {
      const closes = closesFence(fence, line);
      states.push(closes ? "close" : "fence");
      fence = closes ? null : fence;
      previousBlank = false;
    } else if (comment) {
      states.push("comment");
      comment = !line.includes("-->");
    } else {
      fence = opensFence(line);
      if (fence) {
        states.push("open");
        continue;
      }
      const blank = line.trim() === "";
      listIndent = nextListIndent(line, listIndent);
      const width = indentWidth(/^[ \t]*/u.exec(line)[0]);
      const codeIndent = listIndent === -1 ? 4 : listIndent + 4;
      const indented =
        !blank &&
        width >= codeIndent &&
        (previousBlank || states.at(-1) === "indented");
      states.push(indented ? "indented" : "prose");
      comment =
        !indented &&
        line.trimStart().startsWith("<!--") &&
        !line.includes("-->");
      previousBlank = blank;
    }
  }
  return states;
};

const isCode = (state) => state !== "prose";

// CommonMark HTML blocks, whose lines stay raw HTML: Markdown written there
// shows as text, while GitHub turned `[[…]]` in them into links.
const HTML_BLOCK_RAW = /^ {0,3}<(?<tag>pre|script|style|textarea)(?:[\s>]|$)/iu;
const HTML_BLOCK_TAG = new RegExp(
  String.raw`^ {0,3}<\/?(?:${[
    "address article aside base basefont blockquote body caption center col",
    "colgroup dd details dialog dir div dl dt fieldset figcaption figure footer",
    "form frame frameset h1 h2 h3 h4 h5 h6 head header hr html iframe legend",
    "li link main menu menuitem nav noframes ol optgroup option p param search",
    "section summary table tbody td tfoot th thead title tr track ul",
  ]
    .join(" ")
    .replaceAll(" ", "|")})(?:[\s>]|\/>|$)`,
  "iu"
);
const HTML_BLOCK_LONE_TAG =
  /^ {0,3}(?:<[A-Za-z][\w-]*(?:\s+[^<>]*)?\/?>|<\/[A-Za-z][\w-]*\s*>)[ \t]*$/u;

/** The HTML block opening at `index`: `until` is its closing tag, or null when a blank line ends it. */
const htmlBlockStart = (lines, index) => {
  const line = lines[index];
  const raw = HTML_BLOCK_RAW.exec(line);
  if (raw) {
    return { until: new RegExp(String.raw`</${raw.groups.tag}\s*>`, "iu") };
  }
  const previousBlank = index === 0 || lines[index - 1].trim() === "";
  return HTML_BLOCK_TAG.test(line) ||
    (previousBlank && HTML_BLOCK_LONE_TAG.test(line))
    ? { until: null }
    : null;
};

/** The indexes of prose lines inside an HTML block. */
const htmlBlockLines = (lines, states) => {
  const inside = new Set();
  let block = null;
  for (const [index, line] of lines.entries()) {
    if (states[index] !== "prose") {
      block = null;
      continue;
    }
    block ??= htmlBlockStart(lines, index);
    if (block === null || (block.until === null && line.trim() === "")) {
      block = null;
      continue;
    }
    inside.add(index);
    if (block.until?.test(line)) {
      block = null;
    }
  }
  return inside;
};

/** The lines of the paragraph ending at `index`, or null if it isn't a plain paragraph. */
const paragraphAbove = (lines, states, index) => {
  let start = index;
  while (
    start > 0 &&
    states[start - 1] === "prose" &&
    lines[start - 1].trim() !== ""
  ) {
    start -= 1;
  }
  if (start === index) {
    return null;
  }
  for (let line = start; line < index; line += 1) {
    const text = lines[line];
    if (
      LIST_ITEM.test(text) ||
      QUOTED.test(text) ||
      ATX.test(text) ||
      DEFINITION.test(text) ||
      /^(?: {4}|\t)/u.test(text) ||
      /^\s*[|<]/u.test(text)
    ) {
      return null;
    }
  }
  return { count: index - start, start };
};

// --- Page content ------------------------------------------------------------------

const removeFoam = (page, lines) => {
  const begin = lines.findIndex((line) => FOAM_BEGIN.test(line));
  const end = lines.findIndex((line) => FOAM_END.test(line));
  if (begin === -1 || end < begin) {
    return lines;
  }
  edit(page, "Foam autogenerated link block removed");
  return [...lines.slice(0, begin), ...lines.slice(end + 1)];
};

/**
 * Top-level alerts → `:::` directives. Blume renders an alert as a callout in
 * `.mdx` too, so one this can't rewrite line by line (indented in a list, or
 * with lazy lines) stays as written and only makes the page `.mdx`.
 */
const convertAlerts = (page, lines, states) => {
  const out = [];
  let converted = 0;
  let kept = 0;
  for (let index = 0; index < lines.length; index += 1) {
    const start =
      states[index] === "prose" ? ALERT_START.exec(lines[index]) : null;
    if (start === null) {
      if (states[index] === "prose" && ANY_ALERT.test(lines[index])) {
        if (/^[ \t]/u.test(lines[index])) {
          kept += 1;
        } else {
          review(
            page,
            index + 1,
            "a GitHub alert with text after its marker: convert it by hand"
          );
        }
      }
      out.push(lines[index]);
      continue;
    }
    let end = index + 1;
    while (end < lines.length && QUOTED.test(lines[end])) {
      end += 1;
    }
    const body = lines
      .slice(index + 1, end)
      .map((line) => line.replace(/^ {0,3}>[ \t]?/u, ""));
    if (end < lines.length && lines[end].trim() !== "") {
      kept += 1;
      out.push(lines[index]);
      continue;
    }
    if (body.every((line) => line.trim() === "")) {
      review(
        page,
        index + 1,
        "a GitHub alert with no body lines: convert it by hand"
      );
      out.push(lines[index]);
      continue;
    }
    while (body[0].trim() === "") {
      body.shift();
    }
    while (body.at(-1).trim() === "") {
      body.pop();
    }
    const fence = body.some((line) => /^\s*:{3,}/u.test(line)) ? "::::" : ":::";
    out.push(
      `${fence}${ALERTS[start.groups.type.toLowerCase()]}`,
      ...body,
      fence
    );
    converted += 1;
    index = end - 1;
  }
  if (converted > 0) {
    edit(page, "GitHub alert → ::: directive", converted);
  }
  if (kept > 0) {
    edit(page, "indented or lazy GitHub alert kept: a callout in .mdx", kept);
  }
  return { converted, kept, lines: out };
};

const headingText = (rest) =>
  rest.replace(HEADING_MARKER, "").replace(CLOSING_HASHES, "").trim();

/** The page's heading plan: the leading H1 to delete, and whether to demote. */
const planHeadings = (lines, states, title) => {
  const first = lines.findIndex(
    (line, index) => states[index] === "prose" && line.trim() !== ""
  );
  let deleted = [];
  if (first !== -1) {
    const atx = ATX.exec(lines[first]);
    const underline = SETEXT.exec(lines[first + 1] ?? "");
    if (atx && atx.groups.prefix === "" && atx.groups.hashes === "#") {
      deleted =
        comparable(headingText(atx.groups.rest)) === comparable(title)
          ? [first]
          : [];
    } else if (
      underline?.groups.marker.startsWith("=") &&
      states[first + 1] === "prose" &&
      comparable(lines[first]) === comparable(title)
    ) {
      deleted = [first, first + 1];
    }
  }
  const skip = new Set(deleted);
  const hasH1 = lines.some((line, index) => {
    if (skip.has(index) || states[index] !== "prose") {
      return false;
    }
    if (ATX.exec(line)?.groups.hashes === "#") {
      return true;
    }
    return (
      SETEXT.exec(line)?.groups.marker.startsWith("=") === true &&
      paragraphAbove(lines, states, index) !== null
    );
  });
  return { deleted: skip, hasH1 };
};

const pinNamedAnchor = (page, line, index) => {
  const atx = ATX.exec(line);
  const anchor = atx ? NAMED_ANCHOR.exec(atx.groups.rest) : null;
  if (anchor === null) {
    return line;
  }
  if (HEADING_MARKER.test(atx.groups.rest)) {
    review(
      page,
      index + 1,
      "a heading with both <a name> and an id marker: keep one"
    );
    return line;
  }
  const text = atx.groups.rest.replace(NAMED_ANCHOR, "").trim();
  edit(page, "<a name> in a heading → [#id]");
  return `${atx.groups.prefix}${atx.groups.hashes} ${text} [#${anchor.groups.id}]`;
};

const demoteAtx = (line) => {
  const atx = ATX.exec(line);
  if (atx === null || atx.groups.hashes.length >= HEADING_LEVELS) {
    return line;
  }
  return `${atx.groups.prefix}#${atx.groups.hashes}${atx.groups.rest}`;
};

/** Setext headings → ATX one level down, on a page whose headings are demoted. */
const demoteSetext = (page, lines, states) => {
  const out = [...lines];
  for (let index = 0; index < lines.length; index += 1) {
    const underline =
      states[index] === "prose" ? SETEXT.exec(lines[index]) : null;
    const paragraph = underline ? paragraphAbove(lines, states, index) : null;
    if (paragraph === null) {
      continue;
    }
    const level = underline.groups.marker.startsWith("=") ? 2 : 3;
    if (paragraph.count > 1) {
      review(
        page,
        index + 1,
        `a ${paragraph.count}-line setext heading can't be demoted: rewrite it as one ${"#".repeat(level)} line`
      );
      continue;
    }
    out[paragraph.start] =
      `${"#".repeat(level)} ${lines[paragraph.start].trim()}`;
    out[index] = null;
    edit(page, "setext heading → ATX, demoted");
  }
  return out.filter((line) => line !== null);
};

const convertFenceInfo = (page, line, index) => {
  const open = FENCE.exec(line);
  const [language = "", ...rest] = open.groups.info.trim().split(/\s+/u);
  const lower = language.toLowerCase();
  const mapped = FENCE_LANGUAGES[lower] ?? lower;
  if (DROPPED_FENCES.has(lower)) {
    review(
      page,
      index + 1,
      `a ${lower} block renders as code in Blume: maps and 3D models drop`
    );
  }
  if (mapped === language) {
    return { language: lower, line };
  }
  edit(page, `fence language ${language} → ${mapped}`);
  const info = [mapped, ...rest].join(" ");
  return {
    language: mapped,
    line: `${open.groups.prefix}${open.groups.marker}${info}`,
  };
};

/** Delete link definitions a same-label definition above already shadows, and rewrite the rest. */
const convertDefinition = (ctx, line, index, lines, seen) => {
  const definition = DEFINITION.exec(line);
  const previous = lines[index - 1] ?? "";
  const startsBlock =
    index === 0 ||
    previous.trim() === "" ||
    DEFINITION.test(previous) ||
    ATX.test(previous) ||
    /^\s*<!--[\s\S]*-->\s*$/u.test(previous) ||
    previous.includes("-->");
  if (definition === null || !startsBlock) {
    return { isDefinition: false, line };
  }
  const label = definition.groups.label
    .toLowerCase()
    .replaceAll(/\s+/gu, " ")
    .trim();
  if (seen.has(label)) {
    edit(ctx.page, "shadowed duplicate link definition removed");
    return { isDefinition: true, line: null };
  }
  seen.add(label);
  const result = rewriteHref(ctx, definition.groups.dest);
  if (result === null || result.unlink) {
    return { isDefinition: true, line };
  }
  const { indent, rest } = definition.groups;
  return {
    isDefinition: true,
    line: `${indent}[${definition.groups.label}]: ${result.href}${rest}`,
  };
};

const RAW_IMG_SRC =
  /<img\b[^<>]*?\bsrc\s*=\s*(?<quote>["'])(?<src>[^"']*)\k<quote>/giu;

/**
 * A raw `<img>` of a wiki file inside other HTML: its `src` reads from the
 * wiki root, not the page's new folder, so it needs a hand.
 */
const reviewRawImages = (ctx, line) => {
  for (const match of mask(line).matchAll(RAW_IMG_SRC)) {
    const found = wikiFileOf(ctx, match.groups.src);
    if (found?.file) {
      const file = `${ctx.content}/${found.file}`;
      review(
        ctx.page,
        ctx.line,
        `raw <img src="${match.groups.src}"> shows a file stored in the wiki: copy it to ${file} and point src at ${relativeAsset(ctx.dest, file)}, which Blume publishes with the page, or make it a Markdown image`
      );
    }
  }
};

const convertRawImageLine = (ctx, line, previous) => {
  const img = RAW_IMG_LINE.exec(line);
  if (img === null || (previous ?? "").trim() !== "") {
    reviewRawImages(ctx, line);
    return line;
  }
  const attribute = (name) =>
    new RegExp(
      String.raw`\b${name}\s*=\s*(?<quote>["'])(?<value>[^"']*)\k<quote>`,
      "iu"
    ).exec(img.groups.attributes)?.groups.value ?? null;
  const srcValue = attribute("src");
  const found = srcValue ? wikiFileOf(ctx, srcValue) : null;
  if (found === null || found.outside) {
    return line;
  }
  const src = rewriteImage(ctx, srcValue);
  if (src === null || src === "") {
    return src === "" ? "" : line;
  }
  const dropped = ["width", "height", "align"]
    .map((name) => [name, attribute(name)])
    .filter(([, value]) => value !== null)
    .map(([name, value]) => `${name}=${value}`);
  if (dropped.length > 0) {
    review(
      ctx.page,
      ctx.line,
      `raw <img> → Markdown image; dropped ${dropped.join(", ")}`
    );
  }
  edit(ctx.page, "raw <img> → Markdown image");
  return `${img.groups.indent}![${attribute("alt") ?? ""}](${src})`;
};

// --- MDX safety ----------------------------------------------------------------------

const commentText = (text) =>
  text
    .replace(/^\s*<!--/u, "")
    .replace(/--!?>\s*$/u, "")
    .replaceAll("*/", "* /")
    .replaceAll(/\s+/gu, " ")
    .trim();

const mdxComments = (page, lines, states) => {
  const out = [];
  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index];
    if (
      states[index] === "prose" &&
      line.trimStart().startsWith("<!--") &&
      !line.includes("-->")
    ) {
      let end = index;
      while (end + 1 < lines.length && states[end + 1] === "comment") {
        end += 1;
      }
      const [indent] = /^[ \t]*/u.exec(line);
      out.push(
        `${indent}{/* ${commentText(lines.slice(index, end + 1).join(" "))} */}`
      );
      edit(page, "HTML comment → MDX comment");
      index = end;
      continue;
    }
    if (states[index] !== "prose") {
      out.push(line);
      continue;
    }
    out.push(
      replaceOutside(
        line,
        /<!--(?<text>[\s\S]*?)-->/dgu,
        (group) => {
          edit(page, "HTML comment → MDX comment");
          return `{/* ${commentText(group("text"))} */}`;
        },
        { comments: false }
      )
    );
  }
  return out;
};

const mdxLine = (page, line, index) => {
  let next = replaceOutside(line, ANGLE_AUTOLINK, (group) => {
    edit(page, "<https://…> autolink → link");
    return `[${group("url")}](${group("url")})`;
  });
  next = replaceOutside(next, VOID_TAG, (group) => {
    edit(page, "void tag closed");
    return `<${group("tag")}${group("attributes").trimEnd()} />`;
  });
  const strays = replaceOutside(
    next,
    STRAY_ANGLE,
    () => {
      edit(page, "bare < → &lt;");
      return "&lt;";
    },
    { destinations: true }
  );
  const braces = replaceOutside(
    strays,
    BRACE,
    (group, original) => {
      edit(page, "brace in prose escaped");
      return `\\${original}`;
    },
    { destinations: true, tags: true }
  );
  for (const match of mask(braces).matchAll(OPEN_TAG)) {
    if (!HTML_TAGS.has(match.groups.tag)) {
      review(
        page,
        index + 1,
        `<${match.groups.tag}> reads as a JSX element in MDX: escape it or put it in code`
      );
    }
  }
  return braces;
};

const HTML_BLOCK = /<(?:center|details|div|li|ol|p|summary|table|td|tr|ul)\b/iu;

/** Whether the indented block starting at `index` sits at the top level, not inside a list. */
const topLevelBlock = (lines, states, index) => {
  for (let line = index - 1; line >= 0; line -= 1) {
    if (lines[line].trim() !== "" && states[line] !== "indented") {
      return !LIST_ITEM.test(lines[line]) && /^\S/u.test(lines[line]);
    }
  }
  return true;
};

/** The last line of the indented block starting at `index` (blank lines inside it included). */
const indentedBlockEnd = (lines, states, index) => {
  let end = index;
  for (let line = index + 1; line < lines.length; line += 1) {
    if (states[line] === "indented") {
      end = line;
    } else if (lines[line].trim() !== "") {
      break;
    }
  }
  return end;
};

/** MDX has no indented code: fence each top-level indented block, and report the rest. */
const fenceIndentedCode = (page, lines, states) => {
  const out = [];
  for (let index = 0; index < lines.length; index += 1) {
    if (states[index] !== "indented" || states[index - 1] === "indented") {
      out.push(lines[index]);
      continue;
    }
    if (!topLevelBlock(lines, states, index)) {
      review(
        page,
        index + 1,
        "indented code inside a list renders as text in MDX: fence it"
      );
      out.push(lines[index]);
      continue;
    }
    const end = indentedBlockEnd(lines, states, index);
    const body = lines
      .slice(index, end + 1)
      .map((line) => line.replace(/^(?: {4}|\t| {0,3}\t)/u, ""));
    const longest = Math.max(
      2,
      ...body
        .flatMap((line) => line.match(/`+/gu) ?? [])
        .map((run) => run.length)
    );
    const fence = "`".repeat(longest + 1);
    out.push(fence, ...body, fence);
    edit(page, "indented code → fenced block");
    index = end;
  }
  return out;
};

const mdxSafe = (page, lines) => {
  const fenced = fenceIndentedCode(page, lines, lineStates(lines));
  const states = lineStates(fenced);
  const html = fenced.findIndex(
    (line, index) => states[index] === "prose" && HTML_BLOCK.test(mask(line))
  );
  if (html !== -1) {
    review(
      page,
      html + 1,
      "raw HTML blocks in an .mdx page: MDX reads Markdown inside them only with blank lines around it, and fails on interleaved tags; check the build"
    );
  }
  const safe = fenced.map((line, index) =>
    states[index] === "prose" ? mdxLine(page, line, index) : line
  );
  return mdxComments(page, safe, lineStates(safe));
};

// --- One page ---------------------------------------------------------------------------

/** One line of a fence: its opener's language fixed, a ```math fence turned into $$. */
const convertFenceLine = (ctx, line, index, state, flags) => {
  if (state === "open") {
    const fence = convertFenceInfo(ctx.page, line, index);
    const bare = FENCE.exec(fence.line).groups.prefix === "";
    flags.needsMdx ||= fence.language === "mermaid";
    flags.math = fence.language === "math" && bare;
    if (flags.math) {
      edit(ctx.page, "```math → $$ block");
      flags.needsMdx = true;
    }
    return flags.math ? "$$" : fence.line;
  }
  if (state === "close") {
    const out = flags.math ? "$$" : line;
    flags.math = false;
    return out;
  }
  if (state === "indented" && line.includes("[[")) {
    review(
      ctx.page,
      index + 1,
      "[[…]] in an indented block was left alone: check whether it's code"
    );
  }
  return line;
};

const convertProseLine = (ctx, lines, index, plan, seen) => {
  const line = lines[index];
  const definition = convertDefinition(ctx, line, index, lines, seen);
  if (definition.isDefinition) {
    return definition.line;
  }
  // In an HTML block, `#` lines are text, not headings.
  const pinned = ctx.html ? line : pinNamedAnchor(ctx.page, line, index);
  const isHeading = !ctx.html && ATX.test(pinned);
  const imaged = convertRawImageLine(ctx, pinned, lines[index - 1]);
  const converted = convertInline(ctx, imaged, isHeading);
  return plan.hasH1 && isHeading ? demoteAtx(converted) : converted;
};

const trimBlankEdges = (lines) => {
  const first = lines.findIndex((line) => line.trim() !== "");
  if (first === -1) {
    return [];
  }
  const last = lines.findLastIndex((line) => line.trim() !== "");
  return lines.slice(first, last + 1);
};

const convertBody = (ctx, text) => {
  const { page } = ctx;
  const lines = removeFoam(
    page,
    text
      .replace(/^\u{FEFF}/u, "")
      .replaceAll("\r\n", "\n")
      .split("\n")
  );
  const alerts = convertAlerts(page, lines, lineStates(lines));
  const current = alerts.lines;
  const states = lineStates(current);
  const html = htmlBlockLines(current, states);
  const plan = planHeadings(
    current,
    states.map((state, index) => (html.has(index) ? "html" : state)),
    titleOf(ctx.name)
  );
  if (plan.deleted.size > 0) {
    edit(page, "leading H1 repeating the page name removed");
  }
  const flags = { math: false, needsMdx: alerts.converted + alerts.kept > 0 };
  const seen = new Set();
  const out = [];
  for (let index = 0; index < current.length; index += 1) {
    ctx.line = index + 1;
    ctx.html = html.has(index);
    if (plan.deleted.has(index)) {
      continue;
    }
    out.push(
      isCode(states[index])
        ? convertFenceLine(ctx, current[index], index, states[index], flags)
        : convertProseLine(ctx, current, index, plan, seen)
    );
  }
  let result = out.filter((line) => line !== null);
  if (plan.hasH1) {
    edit(page, "page with body H1s: every heading demoted one level");
    result = demoteSetext(page, result, lineStates(result));
  }
  if (flags.needsMdx) {
    result = mdxSafe(page, result);
  }
  return { body: trimBlankEdges(result).join("\n"), needsMdx: flags.needsMdx };
};

const frontmatter = (fields) => {
  const lines = ["---", `title: ${yamlScalar(fields.title)}`];
  if (fields.label) {
    lines.push("sidebar:", `  label: ${yamlScalar(fields.label)}`);
  }
  if (fields.slug) {
    lines.push(`slug: ${yamlScalar(fields.slug)}`);
  }
  lines.push("---");
  return lines.join("\n");
};

// --- The sidebar ------------------------------------------------------------------

const HEADING_LABEL = /^ {0,3}#{1,6}[ \t]+(?<text>.*?)[ \t#]*$/u;
const BOLD_LABEL =
  /^ {0,3}(?:\*\*|__)(?<text>[^*_]+?)(?:\*\*|__)[ \t]*:?[ \t]*$/u;
const ONLY_WIKI_LINK = /^\[\[(?<inner>[^[\]]+)\]\]$/u;
const ONLY_MD_LINK = new RegExp(
  String.raw`^\[(?<text>[^[\]]+)\]\(\s*${DESTINATION}${TITLE}\s*\)$`,
  "u"
);

const parseItem = (content) => {
  const text = content.trim();
  const wiki = ONLY_WIKI_LINK.exec(text);
  if (wiki) {
    const parts = wiki.groups.inner.split(PIPE);
    if (parts.length > 2) {
      return { kind: "other", text };
    }
    const target = (parts[1] ?? parts[0]).trim();
    return { kind: "wiki", label: parts[0].trim(), target };
  }
  const link = ONLY_MD_LINK.exec(text);
  if (link) {
    return {
      dest: unwrapAngle(link.groups.dest),
      kind: "link",
      label: link.groups.text.trim(),
    };
  }
  if (text.includes("[") || text.includes("<")) {
    return { kind: "other", text };
  }
  return { kind: "label", label: plainText(text) };
};

/** `_Sidebar.md` → groups of item trees, in order. */
const parseSidebar = (text) => {
  const groups = [];
  const notes = [];
  let group = null;
  let stack = [];
  const lines = text.replaceAll("\r\n", "\n").split("\n");
  const states = lineStates(lines);
  for (const [index, line] of lines.entries()) {
    if (line.trim() === "" || isCode(states[index])) {
      continue;
    }
    const heading = HEADING_LABEL.exec(line) ?? BOLD_LABEL.exec(line);
    if (heading) {
      group = {
        children: [],
        head: parseItem(heading.groups.text),
        line: index + 1,
      };
      groups.push(group);
      stack = [];
      continue;
    }
    const item = LIST_ITEM.exec(line);
    if (item === null) {
      notes.push(
        `_Sidebar line ${index + 1} has no place in Blume's sidebar: ${line.trim()}`
      );
      continue;
    }
    const indent = indentWidth(item.groups.indent);
    const node = {
      ...parseItem(item.groups.content),
      children: [],
      line: index + 1,
    };
    while (stack.length > 0 && stack.at(-1).indent >= indent) {
      stack.pop();
    }
    if (group === null) {
      group = { children: [], head: null, line: index + 1 };
      groups.push(group);
    }
    const parent = stack.at(-1)?.node ?? group;
    parent.children.push(node);
    stack.push({ indent, node });
  }
  return { groups, notes };
};

/** A sidebar item → `{ kind: "page", name }`, `{ kind: "external", href }`, or `{ kind: "skip", why }`. */
const sidebarTarget = (ctx, node) => {
  if (node.kind === "label" || node.kind === "other") {
    return { kind: "label" };
  }
  let { target } = node;
  if (node.kind === "link") {
    const relative = !URL_SCHEME.test(node.dest) && !node.dest.startsWith("/");
    const absolute = relative
      ? resolveUrl(node.dest, ctx.urls.base)
      : node.dest;
    const wiki = absolute === null ? null : wikiTarget(ctx, absolute);
    if (wiki === null) {
      return URL_SCHEME.test(node.dest)
        ? { href: node.dest, kind: "external" }
        : { kind: "skip", why: `${node.dest} isn't a page` };
    }
    if (wiki.kind !== "page") {
      return { kind: "skip", why: `${node.dest} isn't a page` };
    }
    target = decode(wiki.target);
  }
  if (EXTERNAL.test(target)) {
    return { href: target, kind: "external" };
  }
  if (target.includes("#")) {
    return {
      kind: "skip",
      why: `${target} links a heading, not a page (the page's outline lists it)`,
    };
  }
  const result = resolvePage(ctx.index, target, "");
  if (result.kind !== "content") {
    return {
      kind: "skip",
      why: `${target} names a page that isn't kept (${result.kind})`,
    };
  }
  if (!MARKDOWN.test(ctx.files[result.name])) {
    return {
      kind: "skip",
      why: `${ctx.files[result.name]} isn't Markdown yet (convert it, then rerun)`,
    };
  }
  return { kind: "page", name: result.name };
};

const uniqueName = (taken, base) => {
  let name = base;
  for (let count = 2; taken.has(name); count += 1) {
    name = `${base}-${count}`;
  }
  taken.add(name);
  return name;
};

const fileBase = (index, name) => {
  const route = index.routes[name];
  return route === "/" ? "index" : route.split("/").at(-1);
};

const createLayout = (ctx) => ({
  ctx,
  featured: [],
  folders: new Map([["", new Set()]]),
  metas: new Map(),
  notes: [],
  placed: new Map(),
});

const addMeta = (layout, dir, meta) => {
  layout.metas.set(dir, meta);
  layout.folders.set(dir, new Set());
};

const labelFor = (name, text) =>
  text && comparable(text) !== comparable(titleOf(name)) ? text : null;

const placeNodes = (layout, nodes, dir, pages) => {
  const { ctx } = layout;
  for (const node of nodes) {
    const target = sidebarTarget(ctx, node);
    if (target.kind === "external") {
      layout.featured.push({ href: target.href, label: node.label });
      layout.notes.push(
        `_Sidebar line ${node.line}: external link "${node.label}" → navigation.featured`
      );
      continue;
    }
    if (target.kind === "skip") {
      layout.notes.push(`_Sidebar line ${node.line}: dropped, ${target.why}`);
      continue;
    }
    if (target.kind === "label") {
      if (node.children.length === 0 || node.kind === "other") {
        layout.notes.push(
          `_Sidebar line ${node.line} has no place in Blume's sidebar: ${node.text ?? node.label}`
        );
        continue;
      }
      const folder = uniqueName(
        layout.folders.get(dir),
        `(${slugOf(node.label) || "group"})`
      );
      const sub = posix.join(dir, folder);
      pages.push(folder.slice(1, -1));
      const meta = { display: "group", pages: [], title: node.label };
      addMeta(layout, sub, meta);
      placeNodes(layout, node.children, sub, meta.pages);
      continue;
    }
    const { name } = target;
    if (layout.placed.has(name) || ctx.index.routes[name] === "/") {
      const why =
        ctx.index.routes[name] === "/"
          ? "is the home page, which stays the root index"
          : "is already placed";
      layout.notes.push(
        `_Sidebar line ${node.line}: ${name} ${why}, so this entry is dropped`
      );
      continue;
    }
    const base = fileBase(ctx.index, name);
    const label = labelFor(name, node.label);
    if (node.children.length === 0) {
      layout.placed.set(name, { dir, file: base, label });
      pages.push(base);
      continue;
    }
    const folder = posix.join(dir, uniqueName(layout.folders.get(dir), base));
    layout.placed.set(name, { dir: folder, file: "index", label });
    pages.push(posix.basename(folder));
    const meta = { display: "group", pages: [], title: titleOf(name) };
    addMeta(layout, folder, meta);
    placeNodes(layout, node.children, folder, meta.pages);
  }
};

const placeGroup = (layout, group, rootPages) => {
  const { ctx } = layout;
  if (group.head === null) {
    placeNodes(layout, group.children, "", rootPages);
    return;
  }
  const head = sidebarTarget(ctx, { ...group.head, line: group.line });
  const label = group.head.label ?? group.head.text;
  if (head.kind === "external") {
    layout.featured.push({ href: head.href, label });
    layout.notes.push(
      `_Sidebar line ${group.line}: heading link "${label}" → navigation.featured`
    );
  }
  if (head.kind === "skip") {
    layout.notes.push(
      `_Sidebar line ${group.line}: the heading's link was dropped, ${head.why}`
    );
  }
  if (group.children.length === 0) {
    return;
  }
  if (head.kind === "page" && !layout.placed.has(head.name)) {
    const dir = uniqueName(
      layout.folders.get(""),
      fileBase(ctx.index, head.name)
    );
    layout.placed.set(head.name, {
      dir,
      file: "index",
      label: labelFor(head.name, label),
    });
    rootPages.push(dir);
    const meta = { pages: [], title: label };
    addMeta(layout, dir, meta);
    placeNodes(layout, group.children, dir, meta.pages);
    return;
  }
  const dir = uniqueName(
    layout.folders.get(""),
    `(${slugOf(label) || "group"})`
  );
  rootPages.push(dir.slice(1, -1));
  const meta = { pages: [], title: label };
  addMeta(layout, dir, meta);
  placeNodes(layout, group.children, dir, meta.pages);
};

/** Where every kept page goes, and the meta.ts files that order them. */
const layoutPages = (ctx, sidebar) => {
  const layout = createLayout(ctx);
  const contentPages = [...ctx.index.kinds]
    .filter(
      ([name, kind]) =>
        kind === "content" &&
        ctx.index.routes[name] !== "/" &&
        MARKDOWN.test(ctx.files[name])
    )
    .map(([name]) => name);
  if (sidebar === null) {
    for (const name of contentPages) {
      layout.placed.set(name, {
        dir: "",
        file: fileBase(ctx.index, name),
        label: null,
      });
    }
    return layout;
  }
  const rootPages = [];
  layout.notes.push(...sidebar.notes);
  for (const group of sidebar.groups) {
    placeGroup(layout, group, rootPages);
  }
  const unlisted = contentPages
    .filter((name) => !layout.placed.has(name))
    .toSorted((left, right) =>
      compareText(titleOf(left).toLowerCase(), titleOf(right).toLowerCase())
    );
  if (unlisted.length > 0) {
    const dir = uniqueName(layout.folders.get(""), "(more)");
    rootPages.push(dir.slice(1, -1));
    addMeta(layout, dir, {
      collapsed: true,
      display: "group",
      pages: unlisted.map((name) => fileBase(ctx.index, name)),
      title: "More pages",
    });
    for (const name of unlisted) {
      layout.placed.set(name, {
        dir,
        file: fileBase(ctx.index, name),
        label: null,
      });
    }
  }
  layout.metas.set("", { pages: rootPages });
  return layout;
};

const metaSource = (meta) => {
  const lines = [
    'import { defineMeta } from "blume";',
    "",
    "export default defineMeta({",
  ];
  for (const key of ["title", "display", "collapsed", "pages"]) {
    if (meta[key] !== undefined) {
      const value = Array.isArray(meta[key])
        ? `[\n${meta[key].map((item) => `    ${JSON.stringify(item)},`).join("\n")}\n  ]`
        : JSON.stringify(meta[key]);
      lines.push(`  ${key}: ${value},`);
    }
  }
  lines.push("});", "");
  return lines.join("\n");
};

// --- convert ---------------------------------------------------------------------------

const readTables = (root) => {
  const routesFile = path.join(root, ROUTES_FILE);
  const filesFile = path.join(root, FILES_FILE);
  if (!existsSync(routesFile) || !existsSync(filesFile)) {
    throw new Error(
      `no ${ROUTES_FILE}/${FILES_FILE} here: run \`routes --write\` first`
    );
  }
  const routes = readJson(routesFile);
  const files = readJson(filesFile);
  for (const [name, value] of Object.entries(routes)) {
    if (value !== null && !/^(?:\/|https?:\/\/)/u.test(String(value))) {
      throw new Error(
        `${ROUTES_FILE}: "${name}" must map to a route, a URL, or null`
      );
    }
    if (!(name in files)) {
      throw new Error(`${FILES_FILE} has no file for "${name}"`);
    }
  }
  return { files, routes };
};

const findChrome = (files, pattern) =>
  files
    .filter((file) => !file.includes("/") && pattern.test(file))
    .toSorted(
      (left, right) =>
        Number(MARKDOWN.test(right)) - Number(MARKDOWN.test(left))
    )[0] ?? null;

const planPage = (ctx, layout, name, source) => {
  const place = layout.placed.get(name) ?? {
    dir: "",
    file: "index",
    label: null,
  };
  const page = createPage(source, name);
  const draft = posix.join(ctx.content, place.dir, `${place.file}.md`);
  const pageCtx = {
    ...ctx,
    dest: draft,
    done: new Set(),
    html: false,
    line: 0,
    name,
    page,
  };
  const { body, needsMdx } = convertBody(
    pageCtx,
    readFileSync(path.join(ctx.root, source), "utf-8")
  );
  const dest = needsMdx ? draft.replace(/\.md$/u, ".mdx") : draft;
  const route = ctx.index.routes[name];
  const slug =
    derivedRoute(posix.relative(ctx.content, dest)) === route
      ? null
      : route.slice(1);
  if (slug) {
    edit(page, "slug pinned");
  }
  if (needsMdx) {
    edit(page, "renamed to .mdx");
  }
  const head = frontmatter({ label: place.label, slug, title: titleOf(name) });
  return { dest, page, text: `${head}\n\n${body}\n` };
};

const leftBehind = (ctx, files, pages, moved) => {
  const kept = new Set(moved);
  const lines = [];
  for (const [name, kind] of ctx.index.kinds) {
    const file = ctx.files[name];
    if (kind !== "content" && existsSync(path.join(ctx.root, file))) {
      lines.push(`${file} (${kind === "moved" ? "moved notice" : "left out"})`);
    }
  }
  const served = new Set(Object.values(ctx.files));
  for (const file of pages) {
    if (!served.has(file)) {
      lines.push(`${file} (never served: another file has its name)`);
    }
  }
  const assets = files.filter(
    (file) =>
      !MARKUP.test(file) &&
      !CHROME.test(posix.basename(file)) &&
      !PROJECT_FILES.has(file) &&
      !kept.has(file)
  );
  return { assets, pages: lines.toSorted(compareText) };
};

const siteNotes = (root, files, sidebarFile, layout) => {
  const notes = [...layout.notes];
  if (sidebarFile && !MARKDOWN.test(sidebarFile)) {
    notes.push(`${sidebarFile} isn't Markdown: rebuild the groups by hand`);
  }
  for (const file of files) {
    if (file.includes("/") && CHROME.test(posix.basename(file))) {
      notes.push(
        `${file} replaced the sidebar or footer for its folder: map that folder by hand (i18n or a tab)`
      );
    }
  }
  const footer = findChrome(files, FOOTER);
  if (footer) {
    const text = readFileSync(path.join(root, footer), "utf-8")
      .trim()
      .split("\n")
      .slice(0, MAX_NOTICE_LINES);
    notes.push(
      `${footer}: ${text.join(" / ")} (links → footer.links; a copyright line → footer.copyright; a "contribute to this wiki" footer drops with its link)`
    );
  }
  return notes;
};

const planAll = (ctx, layout) => {
  const results = [];
  const unconverted = [];
  let already = 0;
  for (const [name, kind] of ctx.index.kinds) {
    const source = ctx.files[name];
    if (kind === "content" && !MARKDOWN.test(source)) {
      unconverted.push(source);
    } else if (kind === "content" && existsSync(path.join(ctx.root, source))) {
      results.push(planPage(ctx, layout, name, source));
    } else if (kind === "content") {
      already += 1;
    }
  }
  return { already, results, unconverted };
};

const writeConversion = (ctx, results, metas) => {
  const { content, root } = ctx;
  for (const result of results) {
    const destination = path.join(root, result.dest);
    mkdirSync(path.dirname(destination), { recursive: true });
    writeFileSync(destination, result.text);
    if (result.dest !== result.page.file) {
      rmSync(path.join(root, result.page.file));
    }
  }
  for (const image of [...ctx.images].toSorted(compareText)) {
    const from = path.join(root, image);
    if (existsSync(from)) {
      mkdirSync(path.join(root, content, path.dirname(image)), {
        recursive: true,
      });
      renameSync(from, path.join(root, content, image));
    }
  }
  for (const [dir, meta] of metas) {
    const file = path.join(root, content, dir, "meta.ts");
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, metaSource(meta));
  }
};

const convert = (root, options) => {
  const repo = options.get("repo") ?? "";
  if (!REPO.test(repo)) {
    throw new Error("convert needs --repo <owner/repo>");
  }
  const content = options.get("content") || "docs";
  const tables = readTables(root);
  const { files, pages } = listPages(root, content);
  const ctx = {
    content,
    emoji: loadEmoji(options.get("emoji")),
    // Files only: after a first run, `docs/<route>/` folders exist, and on a
    // case-insensitive disk `docs/Some-Page` would otherwise name one.
    fileExists: (file) =>
      isFile(path.join(root, file)) || isFile(path.join(root, content, file)),
    files: tables.files,
    images: new Set(),
    index: classify(tables.routes),
    root,
    urls: repoUrls(repo, options.get("mirror")),
  };
  const sidebarFile = findChrome(files, SIDEBAR);
  const harvested =
    sidebarFile === null && existsSync(path.join(root, content, "meta.ts"));
  const sidebar =
    sidebarFile && MARKDOWN.test(sidebarFile)
      ? parseSidebar(readFileSync(path.join(root, sidebarFile), "utf-8"))
      : null;
  const layout = layoutPages(ctx, sidebar);
  const planned = planAll(ctx, layout);
  const metas = sidebar === null || harvested ? [] : [...layout.metas];
  if (options.has("write")) {
    writeConversion(ctx, planned.results, metas);
  }
  return {
    ...planned,
    featured: layout.featured,
    images: [...ctx.images].toSorted(compareText),
    left: leftBehind(ctx, files, pages, ctx.images),
    metas: metas.map(([dir]) => posix.join(content, dir, "meta.ts")),
    notes: siteNotes(root, files, sidebarFile, layout),
  };
};

// --- routes ----------------------------------------------------------------------------

const noticeTarget = (root, file, urls, routes) => {
  const text = readFileSync(path.join(root, file), "utf-8");
  const lines = text.split("\n").filter((line) => line.trim() !== "");
  if (lines.length > MAX_NOTICE_LINES || !MOVED_NOTICE.test(text)) {
    return null;
  }
  const url = FIRST_URL.exec(text)?.[0] ?? null;
  const wiki = url && urls ? urls.wiki.exec(url) : null;
  if (wiki) {
    const name = decode((wiki.groups.rest ?? "/Home").slice(1));
    const own = Object.keys(routes).find((key) => keyOf(key) === keyOf(name));
    return own ? `${routes[own]}${wiki.groups.hash ?? ""}` : url;
  }
  return url;
};

const looksNotContent = (root, file) => {
  const folders = file.split("/").slice(0, -1);
  if (folders.some((folder) => NOT_CONTENT_FOLDERS.has(folder.toLowerCase()))) {
    return true;
  }
  if (!file.includes("/") && NOT_CONTENT.has(pageNameOf(file).toLowerCase())) {
    return true;
  }
  const text = readFileSync(path.join(root, file), "utf-8").trim();
  return (
    text.split("\n").length === 1 && text.length < 40 && !text.includes("](")
  );
};

const routesCommand = (root, options) => {
  const content = options.get("content") || "docs";
  const repo = options.get("repo") ?? "";
  const urls = REPO.test(repo) ? repoUrls(repo, null) : null;
  const { pages } = listPages(root, content);
  const table = buildTable(pages);
  const moved = [];
  const notContent = [];
  for (const [name, file] of Object.entries(table.sources)) {
    const target = MARKDOWN.test(file)
      ? noticeTarget(root, file, urls, table.routes)
      : null;
    if (target) {
      moved.push(`"${name}": "${target}"`);
    } else if (looksNotContent(root, file)) {
      notContent.push(`"${name}": null  (${file})`);
    }
  }
  const digitLed = Object.entries(table.routes)
    .filter(([, route]) => ORDERING_PREFIX.test(route.slice(1)))
    .map(([name, route]) => `${name} → ${route} (convert pins its slug)`);
  const other = pages.filter((file) => !MARKDOWN.test(file));
  const routesFile = path.join(root, ROUTES_FILE);
  const existing = existsSync(routesFile) ? readJson(routesFile) : null;
  const changes = [];
  if (existing) {
    for (const name of Object.keys(table.routes)) {
      if (!(name in existing)) {
        changes.push(`not in ${ROUTES_FILE}: ${name} (${table.sources[name]})`);
      }
    }
    for (const name of Object.keys(existing)) {
      if (!(name in table.routes)) {
        changes.push(`in ${ROUTES_FILE} but not a page here: ${name}`);
      }
    }
  } else if (options.has("write")) {
    writeJson(routesFile, table.routes);
    writeJson(path.join(root, FILES_FILE), table.sources);
  }
  return {
    changes,
    digitLed,
    existing: existing !== null,
    moved,
    notContent,
    other,
    table,
  };
};

// --- stubs -------------------------------------------------------------------------------

const stubWriter = (root, write, changes) => (file, text) => {
  const target = path.join(root, file);
  if (existsSync(target) && readFileSync(target, "utf-8") === text) {
    return;
  }
  changes.push(file);
  if (write) {
    writeFileSync(target, text);
  }
};

const removeFile = (root, write, changes, file) => {
  changes.push(`${file} (removed)`);
  if (write) {
    rmSync(path.join(root, file));
  }
};

const noticeOnly = (root, tables, all, put, notice) => {
  const home = Object.keys(tables.routes).find(
    (name) => keyOf(name) === "home"
  );
  const targets = [
    home ? tables.files[home] : null,
    findChrome(all, SIDEBAR) ?? "_Sidebar.md",
  ];
  for (const file of targets.filter(Boolean)) {
    const target = path.join(root, file);
    const text = existsSync(target) ? readFileSync(target, "utf-8") : "";
    if (!text.startsWith(notice)) {
      put(file, `${notice}\n\n${text}`);
    }
  }
};

const stubsCommand = (root, options) => {
  const site = (options.get("site") ?? "").replace(/\/+$/u, "");
  if (!/^https?:\/\//u.test(site)) {
    throw new Error("stubs needs --site <the new site's URL>");
  }
  if (existsSync(path.join(root, "blume.config.ts"))) {
    throw new Error(
      "stubs runs in a fresh clone of the wiki, not in the Blume project: clone the wiki elsewhere and copy the two tables in"
    );
  }
  const tables = readTables(root);
  const changes = [];
  const left = [];
  const write = options.has("write");
  const put = stubWriter(root, write, changes);
  const notice = `**The docs have moved to <${site}>.**`;
  const all = walk(root, new Set());
  if (options.has("notice-only")) {
    noticeOnly(root, tables, all, put, notice);
    return { changes, left };
  }
  for (const [name, value] of Object.entries(tables.routes)) {
    const source = tables.files[name];
    if (value === null) {
      left.push(source);
      continue;
    }
    const url = URL_SCHEME.test(value) ? value : `${site}${value}`;
    const stub = source.replace(/\.[^./]+$/u, ".md");
    put(stub, `**This page has moved to <${url}>.**\n`);
    if (stub !== source && existsSync(path.join(root, source))) {
      removeFile(root, write, changes, source);
    }
  }
  for (const file of all) {
    if (CHROME.test(posix.basename(file)) && file !== "_Sidebar.md") {
      removeFile(root, write, changes, file);
    }
  }
  put("_Sidebar.md", `${notice}\n`);
  return { changes, left };
};

// --- check ---------------------------------------------------------------------------------

const PAGE_IN_URL =
  /\/wiki(?:\/(?<page>[^?#]*))?(?:\?[^#]*)?(?:#(?<anchor>.*))?$/u;

const idsOf = (html) =>
  new Set([...html.matchAll(ID_ATTRIBUTE)].map((match) => match.groups.id));

/** Where the pages are: a server build (`vercel()`, `node()`, …) keeps them in `client/`. */
const pagesRoot = (dist) => {
  const client = path.join(dist, "client");
  return existsSync(client) &&
    statSync(client).isDirectory() &&
    !existsSync(path.join(dist, "index.html"))
    ? client
    : dist;
};

const checkRoute = (dist, route) => {
  const [page, anchor = ""] = route.split("#");
  const file =
    page === "/"
      ? path.join(dist, "index.html")
      : path.join(dist, decode(page), "index.html");
  if (!existsSync(file)) {
    return { status: "missing page" };
  }
  if (anchor === "") {
    return { status: "ok" };
  }
  const ids = idsOf(readFileSync(file, "utf-8"));
  if (ids.has(decode(anchor))) {
    return { status: "ok" };
  }
  const words = decode(anchor)
    .toLowerCase()
    .split(/[^\p{L}\p{N}]+/u)
    .filter(Boolean);
  const suggestions = [...ids]
    .filter(
      (id) => words.length > 0 && words.every((word) => id.includes(word))
    )
    .slice(0, MAX_ID_SUGGESTIONS);
  return { status: "missing anchor", suggestions };
};

const checkCommand = (root, options, urls) => {
  const dist = pagesRoot(path.join(root, options.get("dist") || "dist"));
  const { routes } = readTables(root);
  const index = classify(routes);
  const lines = [];
  let problems = 0;
  const report = (label, route) => {
    const result = checkRoute(dist, route);
    if (result.status !== "ok") {
      problems += 1;
    }
    const hint = result.suggestions?.length
      ? ` (ids like: ${result.suggestions.join(", ")})`
      : "";
    lines.push(
      `${result.status === "ok" ? "ok" : result.status.toUpperCase()}  ${label} → ${route}${hint}`
    );
  };
  if (urls.length === 0) {
    for (const [name, value] of Object.entries(routes)) {
      if (value !== null && !URL_SCHEME.test(value)) {
        report(name, value);
      }
    }
    return { lines, problems };
  }
  for (const url of urls) {
    const match = PAGE_IN_URL.exec(url);
    const target = `${decode(match?.groups.page || "Home")}${match?.groups.anchor ? `#${match.groups.anchor}` : ""}`;
    const result = resolvePage(index, target, "Home");
    if (result.href?.startsWith("/")) {
      report(url, result.href);
    } else if (result.kind === "moved") {
      lines.push(`moved  ${url} → ${result.href}`);
    } else {
      problems += 1;
      lines.push(`${result.kind.toUpperCase()}  ${url}`);
    }
  }
  return { lines, problems };
};

