// --- Small helpers --------------------------------------------------------------

const compareText = (left, right) => {
  if (left < right) {
    return -1;
  }
  return left > right ? 1 : 0;
};

const escapeRegExp = (text) =>
  text.replaceAll(/[$()*+.?[\\\]^{|}]/gu, String.raw`\$&`);

const decode = (text) => {
  try {
    return decodeURIComponent(text);
  } catch {
    return text;
  }
};

/** A page's new route segment: lowercase, apostrophes dropped, other runs → `-`. */
const slugOf = (name) =>
  name
    .normalize("NFC")
    .replaceAll(/['\p{Pf}]/gu, "")
    .toLowerCase()
    .replaceAll(/[^\p{L}\p{N}]+/gu, "-")
    .replaceAll(/^-+|-+$/gu, "");

/** GitHub's page name for a file: its base name minus the last extension. */
const pageNameOf = (file) =>
  posix.basename(file).replace(MARKUP, "").replaceAll(" ", "-");

/** How GitHub matched a name: case-insensitive, spaces read as `-`. */
const keyOf = (name) => name.trim().replaceAll(" ", "-").toLowerCase();

const ownRouteOf = (name) =>
  keyOf(name) === "home" ? "/" : `/${slugOf(name)}`;

/** The page name as GitHub showed it above the page. */
const titleOf = (name) =>
  name.replaceAll("-", " ").replaceAll(UNICODE_HYPHEN, "-");

const plainText = (text) =>
  text
    .replaceAll(/[*_`~]/gu, "")
    .replaceAll(/\[(?<text>[^\]]*)\]\([^)]*\)/gu, "$<text>")
    .trim();

const comparable = (text) =>
  plainText(text)
    .toLowerCase()
    .replaceAll(/[^\p{L}\p{N}]/gu, "");

const yamlScalar = (value) =>
  PLAIN_SCALAR.test(value) &&
  !YAML_KEYWORD.test(value) &&
  value.trim() === value
    ? value
    : JSON.stringify(value);

const cleanAnchor = (anchor) => anchor.replace(/^user-content-/u, "");

const unwrapAngle = (dest) =>
  dest.startsWith("<") && dest.endsWith(">") ? dest.slice(1, -1) : dest;

const depthOf = (file) => file.split("/").length;

const byDepthThenName = (left, right) =>
  depthOf(left) - depthOf(right) || compareText(left, right);

/** Blume's route for a file under the content root (ordering prefixes and `(group)` folders dropped). */
const derivedRoute = (relative) => {
  const segments = relative
    .replace(/\.mdx?$/u, "")
    .split("/")
    .filter((segment) => !(segment.startsWith("(") && segment.endsWith(")")))
    .map((segment) => {
      const order = NOT_AN_ORDER.test(segment)
        ? null
        : ORDERING_PREFIX.exec(segment);
      return order ? segment.slice(order.groups.order.length + 1) : segment;
    });
  if (segments.at(-1) === "index") {
    segments.pop();
  }
  return `/${segments.join("/")}`;
};

const relativeAsset = (fromFile, toFile) => {
  const relative = posix.relative(posix.dirname(fromFile), toFile);
  const dotted = relative.startsWith(".") ? relative : `./${relative}`;
  return dotted.replaceAll(" ", "%20");
};

const walk = (root, skip, dir = "") => {
  const files = [];
  const entries = readdirSync(path.join(root, dir), { withFileTypes: true });
  for (const entry of entries.toSorted((left, right) =>
    compareText(left.name, right.name)
  )) {
    const relative = dir ? `${dir}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      if (!skip.has(relative) && !SKIP_DIRS.has(entry.name)) {
        files.push(...walk(root, skip, relative));
      }
    } else {
      files.push(relative);
    }
  }
  return files;
};

const resolveUrl = (href, base) => {
  try {
    return new URL(href, base).href;
  } catch {
    return null;
  }
};

const isFile = (file) => existsSync(file) && statSync(file).isFile();

const readJson = (file) => JSON.parse(readFileSync(file, "utf-8"));

const writeJson = (file, value) =>
  writeFileSync(file, `${JSON.stringify(value, null, 2)}\n`);

const loadEmoji = (file) => {
  const map = new Map();
  if (!file) {
    return map;
  }
  for (const match of readFileSync(file, "utf-8").matchAll(EMOJI_ENTRY)) {
    const points = match.groups.hex
      .split("-")
      .map((hex) => Number.parseInt(hex, 16));
    map.set(match.groups.name, String.fromCodePoint(...points));
  }
  return map;
};

/** `line` with code spans, comments, tags, and link destinations blanked out (same length). */
const blankOut = (span) => DELETED.repeat(span.length);

const mask = (
  line,
  { comments = true, destinations = false, elements = false, tags = false } = {}
) => {
  let masked = line.replaceAll(CODE_SPAN, blankOut);
  if (comments) {
    masked = masked.replaceAll(COMMENT, blankOut);
  }
  if (elements) {
    masked = masked.replaceAll(CODE_ELEMENT, blankOut);
  }
  if (tags) {
    masked = masked.replaceAll(TAG, blankOut);
  }
  if (destinations) {
    masked = masked.replaceAll(LINK_DESTINATION, blankOut);
  }
  return masked;
};

/**
 * Replace each match of `pattern` (a `d`-flagged global regex) found outside
 * code spans and comments. `replace(group, original)` gets the match's text
 * from the real line, and returns the replacement or null to keep it.
 */
const replaceOutside = (line, pattern, replace, options) => {
  const masked = mask(line, options);
  let out = "";
  let last = 0;
  for (const match of masked.matchAll(pattern)) {
    const end = match.index + match[0].length;
    const original = line.slice(match.index, end);
    const group = (name) => {
      const span = match.indices.groups?.[name];
      return span ? line.slice(span[0], span[1]) : null;
    };
    const next = original.includes(DELETED) ? null : replace(group, original);
    out += `${line.slice(last, match.index)}${next ?? original}`;
    last = end;
  }
  return `${out}${line.slice(last)}`;
};

