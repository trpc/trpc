const REPO = /^(?<owner>[\w.-]+)\/(?<name>[\w.-]+)$/u;

const repoUrls = (repo, mirror) => {
  const { owner, name } = REPO.exec(repo).groups;
  const base = `${escapeRegExp(owner)}/${escapeRegExp(name)}`;
  const mirrorMatch = mirror ? REPO.exec(mirror) : null;
  const mirrorBase = mirrorMatch
    ? `${escapeRegExp(mirrorMatch.groups.owner)}/${escapeRegExp(mirrorMatch.groups.name)}`
    : null;
  return {
    angle: new RegExp(
      String.raw`<(?<url>https?://(?:www\.)?github\.com/${base}/wiki(?:[/#][^<>\s]*)?)>`,
      "dgiu"
    ),
    bare: new RegExp(
      String.raw`(?<![\w(<\["'=/])(?<url>https?://(?:www\.)?github\.com/${base}/wiki(?:[/#][^\s<>()[\]"'\u{60}]*)?)`,
      "dgiu"
    ),
    base: `https://github.com/${owner}/${name}/wiki/`,
    mirror: mirrorBase
      ? new RegExp(
          String.raw`^https?://(?:www\.)?github\.com/${mirrorBase}/blob/[^/]+/(?<file>[^?#]+)(?<hash>#.*)?$`,
          "iu"
        )
      : null,
    owner,
    raw: new RegExp(
      String.raw`^https?://raw\.githubusercontent\.com/wiki/${base}/(?<file>[^?#]+)`,
      "iu"
    ),
    repoRoot: new RegExp(String.raw`^/${base}(?:[/?#]|$)`, "iu"),
    wiki: new RegExp(
      String.raw`^(?:https?://(?:www\.)?github\.com)?/${base}/wiki(?<rest>/[^?#]*)?(?:\?[^#]*)?(?<hash>#.*)?$`,
      "iu"
    ),
  };
};

/** The wiki's pages, the way GitHub serves them. */
const listPages = (root, content) => {
  const files = walk(root, new Set([content])).toSorted(byDepthThenName);
  const pages = files.filter((file) => {
    const base = posix.basename(file);
    return MARKUP.test(base) && !CHROME.test(base);
  });
  return { files, pages };
};

const buildTable = (pages) => {
  const routes = {};
  const sources = {};
  const taken = new Map();
  const owners = new Map();
  const shadowed = [];
  const clashes = [];
  for (const file of pages) {
    const name = pageNameOf(file);
    const key = keyOf(name);
    if (taken.has(key)) {
      shadowed.push(`${file} (GitHub served ${taken.get(key)})`);
      continue;
    }
    taken.set(key, file);
    const route = ownRouteOf(name);
    if (owners.has(route)) {
      clashes.push(`${file} and ${owners.get(route)} → ${route}`);
    }
    owners.set(route, file);
    routes[name] = route;
    sources[name] = file;
  }
  return { clashes, routes, shadowed, sources };
};

const kindOf = (name, value, owners) => {
  if (value === null) {
    return "dropped";
  }
  if (URL_SCHEME.test(value) || value.includes("#")) {
    return "moved";
  }
  const owner = owners.get(value);
  return owner && owner !== name ? "moved" : "content";
};

/** Each page's role from the classified table: content, moved, or dropped. */
const classify = (routes) => {
  const owners = new Map(
    Object.keys(routes).map((name) => [ownRouteOf(name), name])
  );
  const kinds = new Map();
  const byKey = new Map();
  for (const [name, value] of Object.entries(routes)) {
    kinds.set(name, kindOf(name, value, owners));
    byKey.set(keyOf(name), name);
  }
  return { byKey, kinds, routes };
};

const findPage = (index, target) =>
  index.byKey.get(keyOf(target)) ??
  index.byKey.get(keyOf(target.replaceAll("_", "-"))) ??
  null;

/** A page target (`Page Name#anchor`) → { kind, name, href }. */
const resolvePage = (index, target, self) => {
  const hashAt = target.indexOf("#");
  const page = hashAt === -1 ? target : target.slice(0, hashAt);
  const anchor = hashAt === -1 ? "" : cleanAnchor(target.slice(hashAt + 1));
  if (page.trim() === "") {
    return anchor
      ? { href: `#${anchor}`, kind: "content", name: self }
      : { kind: "missing", name: target };
  }
  const name =
    findPage(index, page) ?? findPage(index, page.replace(MARKUP, ""));
  if (name === null) {
    return { kind: "missing", name: page };
  }
  const kind = index.kinds.get(name);
  const value = index.routes[name];
  if (kind === "dropped") {
    return { kind, name };
  }
  if (kind === "moved") {
    return { href: value, kind, name };
  }
  return { href: anchor ? `${value}#${anchor}` : value, kind, name };
};

/** What a URL into the wiki names: a page, a file stored in the wiki, or GitHub's UI. */
const wikiTarget = (ctx, href) => {
  const match = ctx.urls.wiki.exec(href);
  if (!match) {
    return null;
  }
  const rest = decode((match.groups.rest ?? "").replace(/^\//u, "")).replace(
    /\/$/u,
    ""
  );
  const hash = match.groups.hash ?? "";
  if (rest === "") {
    return { kind: "page", target: `Home${hash}` };
  }
  if (ctx.fileExists(rest) && !MARKUP.test(rest)) {
    return { file: rest, kind: "file" };
  }
  const [first, ...more] = rest.split("/");
  const revision =
    more.length === 1 && /^(?:_history|[0-9a-f]{7,40})$/iu.test(more[0]);
  if (UI_PAGE.test(first) || revision) {
    return { kind: "ui" };
  }
  if (more.length > 0) {
    // GitHub serves a page's file at its path (`/wiki/dir/Page.md`) raw.
    const name = MARKUP.test(rest)
      ? findPage(ctx.index, pageNameOf(rest))
      : null;
    return name !== null && ctx.files[name] === rest
      ? { kind: "page", raw: true, target: `${name}${hash}` }
      : { kind: "unknown" };
  }
  return { kind: "page", raw: MARKUP.test(first), target: `${first}${hash}` };
};

/** A wiki file an image source names, `{ outside: true }` for a path above the wiki, or null. */
const wikiFileOf = (ctx, src) => {
  const raw = ctx.urls.raw.exec(src);
  if (raw) {
    return { file: decode(raw.groups.file) };
  }
  const mirrored = ctx.urls.mirror?.exec(src);
  if (mirrored) {
    return { file: decode(mirrored.groups.file) };
  }
  if (src.startsWith("#") || src.startsWith("//")) {
    return null;
  }
  const relative = !URL_SCHEME.test(src) && !src.startsWith("/");
  const absolute = relative
    ? resolveUrl(src, `${ctx.urls.base}${encodeURIComponent(ctx.name)}`)
    : src;
  const match = absolute === null ? null : ctx.urls.wiki.exec(absolute);
  if (match) {
    const rest = decode((match.groups.rest ?? "").replace(/^\//u, ""));
    return posix.extname(rest) === "" ? null : { file: rest };
  }
  return relative && absolute !== null ? { outside: true } : null;
};

