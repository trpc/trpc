/**
 * Emits per-document and shared modules from validated documents. Paths and
 * import specifiers are supplied by the caller; output needs no formatter.
 * Generated class names that can't be made unique produce diagnostics instead
 * of output.
 *
 * @internal
 */
import * as Arr from "effect/Array"
import type { GraphQL } from "effect/graphql"
import type { GeneratedFile } from "../Generator.ts"
import type * as Ast from "./Ast.ts"
import { type Diagnostic, make } from "./Diagnostic.ts"
import { print, template } from "./Printer.ts"
import * as SchemaModel from "./SchemaModel.ts"
import { type File, fragmentSpreads, inclusion } from "./Validate.ts"

/** One parsed document file holding only executable definitions. */
export interface DocumentFile extends File {
  /** Absolute path of the `.graphql.ts` emitted for this file. */
  readonly outputPath: string
  /** The source file's base name, used in the header. */
  readonly sourceName: string
}

/** A custom or built-in scalar mapped to a codec export. */
export interface ScalarMapping {
  /** The import specifier as written in the shared module. */
  readonly specifier: string
  readonly exportName: string
}

export interface Options {
  readonly schema: SchemaModel.Schema
  readonly files: ReadonlyArray<DocumentFile>
  /** Absolute path of the shared module. */
  readonly sharedPath: string
  readonly scalars: ReadonlyMap<string, ScalarMapping>
  /** The import specifier one generated file uses for another, from absolute paths. */
  readonly importSpecifier: (from: string, to: string) => string
}

export interface Output {
  readonly files: ReadonlyArray<GeneratedFile>
  readonly errors: ReadonlyArray<Diagnostic>
  /** Custom scalars the operations reach that have no mapping, sorted by name. */
  readonly unmappedScalars: ReadonlyArray<string>
}

export const emit = (options: Options): Output => {
  const emitter = new Emitter(options)
  const errors = emitter.check()
  if (errors.length > 0) return { files: [], errors, unmappedScalars: [] }
  const emitted = options.files.map((file) => emitter.emitFile(file))
  const emitErrors = emitted.flatMap((result) => result.errors)
  if (emitErrors.length > 0) return { files: [], errors: emitErrors, unmappedScalars: [] }
  const shared = emitter.emitShared()
  return { files: [shared.file, ...emitted.map((result) => result.file)], errors: [], unmappedScalars: shared.unmapped }
}

