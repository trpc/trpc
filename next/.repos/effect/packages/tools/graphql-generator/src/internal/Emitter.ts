export const header = (sourceName: string | undefined): string =>
  `// Generated by @effect/graphql-generator${sourceName === undefined ? "" : ` from ${sourceName}`}. Do not edit.`

/** A private-use character marking class references in rendered structs (see `classRef`). */
const classMarker = "\uE000"

/**
 * Escapes `*\/` so text can't end the JSDoc comment it is written into, and
 * the class reference marker so it can't be mistaken for one.
 */
const escapeComment = (text: string): string => text.replace(/\*\//g, "*\\/").replace(/\uE000/g, "\\uE000")

const deprecation = (reason: string): string => escapeComment(reason.replace(/\s*\r?\n\s*/g, " "))

const descriptionLines = (description: string | undefined): Array<string> => {
  if (description === undefined) return []
  const lines = description.split(/\r\n|\r|\n/).map((line) => escapeComment(line.trimEnd()))
  while (lines.length > 0 && lines[0] === "") lines.shift()
  while (lines.length > 0 && lines[lines.length - 1] === "") lines.pop()
  return lines
}

const docLines = (body: ReadonlyArray<string>, tags: ReadonlyArray<string>): Array<string> =>
  body.length > 0 && tags.length > 0 ? [...body, "", ...tags] : [...body, ...tags]

const jsdoc = (lines: ReadonlyArray<string>, indent: string): string => {
  if (lines.length === 0) return ""
  if (lines.length === 1) return `${indent}/** ${lines[0]} */\n`
  return `${indent}/**\n${
    lines.map((line) => line === "" ? `${indent} *` : `${indent} * ${line}`).join("\n")
  }\n${indent} */\n`
}

const deprecatedTag = (reason: string | undefined): Array<string> =>
  reason === undefined ? [] : [`@deprecated ${deprecation(reason)}`]

const defaultTag = (value: SchemaModel.ConstValue | undefined): Array<string> =>
  value === undefined ? [] : [`@default ${escapeComment(printConstValue(value))}`]

/** A const value in GraphQL syntax, for `@default` tags. */
const printConstValue = (value: SchemaModel.ConstValue): string => {
  switch (value._tag) {
    case "IntValue":
    case "FloatValue":
    case "EnumValue":
      return value.value
    case "StringValue":
      return JSON.stringify(value.value)
    case "BooleanValue":
      return String(value.value)
    case "NullValue":
      return "null"
    case "ListValue":
      return `[${value.values.map(printConstValue).join(", ")}]`
    case "ObjectValue":
      return value.fields.length === 0
        ? "{}"
        : `{ ${value.fields.map((field) => `${field.name}: ${printConstValue(field.value)}`).join(", ")} }`
  }
}

const struct = (members: ReadonlyArray<string>, indent: string, schema = "Schema"): string =>
  members.length === 0 ? `${schema}.Struct({})` : `${schema}.Struct({\n${members.join(",\n")}\n${indent}})`

/** Writes out a type reference: `leaf` for its named type, `list` around list types, `nullable` around types without `!`. */
const typeRef = (
  type: SchemaModel.TypeRef,
  leaf: (name: string) => string,
  list: (element: string) => string,
  nullable: (inner: string) => string
): string => {
  const nonNull = (type: SchemaModel.NamedTypeRef | SchemaModel.ListTypeRef): string =>
    type._tag === "ListTypeRef" ? list(typeRef(type.ofType, leaf, list, nullable)) : leaf(type.name)
  return type._tag === "NonNullTypeRef" ? nonNull(type.ofType) : nullable(nonNull(type))
}

const typeSchema = (type: SchemaModel.TypeRef, leaf: (name: string) => string, schema = "Schema"): string =>
  typeRef(type, leaf, (element) => `${schema}.Array(${element})`, (inner) => `${schema}.NullOr(${inner})`)

/**
 * The Schema for a variable or input field: a nullable one, or a non-null one
 * with a default, is `optional`.
 */
const inputSchema = (
  type: SchemaModel.TypeRef,
  hasDefault: boolean,
  ref: (name: string) => string,
  schema = "Schema"
): string => {
  const expression = typeSchema(
    type,
    (name) => name === "String" || name === "Boolean" ? `${schema}.${name}` : ref(name),
    schema
  )
  return hasDefault || type._tag !== "NonNullTypeRef" ? `${schema}.optional(${expression})` : expression
}

/**
 * A struct key. `__proto__` is written as a computed key, because in an
 * object literal the plain form sets the prototype instead of a field.
 */
const propertyKey = (key: string): string => key === "__proto__" ? `["__proto__"]` : key

/** `issue-timeline` → `IssueTimeline`. */
const pascalCase = (text: string): string =>
  text.split(/[^A-Za-z0-9]+/).map((word) => word.slice(0, 1).toUpperCase() + word.slice(1)).join("")

/** `issue-timeline.graphql` or `issue-timeline.gql` → `IssueTimelineGraphQLGroup`. */
const groupName = (sourceName: string): string => {
  const name = pascalCase(sourceName.replace(/\.(?:graphql|gql)$/, ""))
  return `${/^[0-9]/.test(name) ? `_${name}` : name}GraphQLGroup`
}

const reservedWords: ReadonlySet<string> = new Set([
  "await break case catch class const continue debugger default delete do else enum export extends",
  "false finally for function if implements import in instanceof interface let new null package private",
  "protected public return static super switch this throw true try typeof var void while with yield",
  "any bigint boolean never number object string symbol undefined unknown"
].flatMap((line) => line.split(" ")))

/** Names unavailable for generated bindings or TypeScript type declarations. */
const unbindable = (name: string): boolean => reservedWords.has(name) || name === "arguments" || name === "eval"

/**
 * An alias for each of `names` that can't be bound: `name_`, then more `_`
 * while `taken`. Reserved words hold no `_`, so aliases never collide.
 */
const underscoreAliases = (names: Iterable<string>, taken: ReadonlySet<string>): Map<string, string> => {
  const aliases = new Map<string, string>()
  for (const name of names) {
    if (!unbindable(name)) continue
    let alias = `${name}_`
    while (taken.has(alias)) alias = `${alias}_`
    aliases.set(name, alias)
  }
  return aliases
}

/** Names every per-file module imports, which operations and fragments can't take. */
const importedNames: ReadonlySet<string> = new Set(["Schema", "Shared", "GraphQL", "GraphQLGroup"])

interface BuiltInScalar {
  readonly codec: (schema: string) => string
  /** Whether the codec's Encoded type differs from its Type. */
  readonly transforms: boolean
}

/** The scalars with a default codec in the shared module, in declaration order. */
const builtInSharedScalars: ReadonlyMap<string, BuiltInScalar> = new Map([
  ["Int", { codec: (schema) => `${schema}.Number.check(${schema}.isInt32())`, transforms: false }],
  ["Float", { codec: (schema) => `${schema}.Finite`, transforms: false }],
  ["ID", { codec: (schema) => `${schema}.String`, transforms: false }],
  ["DateTime", { codec: (schema) => `${schema}.DateTimeUtcFromString`, transforms: true }],
  ["URI", { codec: (schema) => `${schema}.String`, transforms: false }]
])

/**
 * Tarjan's strongly connected components of the graph reached from `roots`,
 * in dependency order. Each component's nodes are in the order they were
 * reached.
 */
const stronglyConnectedComponents = (
  roots: Iterable<string>,
  successors: (node: string) => Iterable<string>
): Array<ReadonlyArray<string>> => {
  const index = new Map<string, number>()
  const low = new Map<string, number>()
  const stack: Array<string> = []
  const onStack = new Set<string>()
  const components: Array<ReadonlyArray<string>> = []
  const visit = (node: string): void => {
    const nodeIndex = index.size
    index.set(node, nodeIndex)
    low.set(node, nodeIndex)
    stack.push(node)
    onStack.add(node)
    for (const next of successors(node)) {
      if (!index.has(next)) {
        visit(next)
        low.set(node, Math.min(low.get(node)!, low.get(next)!))
      } else if (onStack.has(next)) {
        low.set(node, Math.min(low.get(node)!, index.get(next)!))
      }
    }
    if (low.get(node) !== nodeIndex) return
    const component = stack.splice(stack.lastIndexOf(node))
    for (const member of component) onStack.delete(member)
    components.push(component)
  }
  for (const root of roots) {
    if (!index.has(root)) visit(root)
  }
  return components
}

